#!/usr/bin/env python3
"""Apply a generated Day 1 domain migration to production and record the evidence.

  SBP=<token> python3 tools/day1/apply_domain.py K [--probe tools/day1/plans/domain_k_probe.sql]

It (1) counts the rows in every table the plan extends, (2) applies the migration, (3) reads back the field map and DT-01
counts, (4) runs an optional zero-residue probe (a DO block that ends in a raised exception carrying its findings), (5) counts
again, and writes docs/day1/evidence/production-apply-domain-<x>-verification.json and rollback_day1_domain_<x>.sql.
The rollback drops the columns and tables the plan added, in this order: triggers, columns, tables, map rows. Functions added
by the hand written logic are listed from the logic file."""
import importlib.util, json, os, re, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DICT = ROOT / "docs/day1/package/T3A-DEV-DAY1-001_Field_Dictionary_v1.3.json"

def q(sql):
    r = urllib.request.Request("https://api.supabase.com/v1/projects/tnjyywtulpdyackmwnca/database/query", data=json.dumps({"query": sql}).encode(),
        headers={"Authorization": "Bearer " + os.environ["SBP"], "Content-Type": "application/json", "User-Agent": "curl/8"}, method="POST")
    try: return json.load(urllib.request.urlopen(r, timeout=180))
    except urllib.error.HTTPError as e: return {"HTTP_ERROR": e.code, "body": e.read().decode()[:700]}

def main(domain, probe):
    spec = importlib.util.spec_from_file_location("plan", ROOT / f"tools/day1/plans/domain_{domain.lower()}.py"); plan = importlib.util.module_from_spec(spec); spec.loader.exec_module(plan)
    F = {f["qualified_name"]: f for f in json.load(open(DICT))["fields"]}
    mig = ROOT / f"supabase/migrations/{plan.MIGRATION}.sql"
    ev = ROOT / "docs/day1/evidence"; tag = domain.lower()
    ext = [t["name"] for t in plan.TABLES if t.get("extend")]
    news = [t["name"] for t in plan.TABLES if not t.get("extend")]
    v = {"domain": domain, "migration": mig.name}
    v["rows_before"] = {t: q(f"select count(*) n from public.{t}")[0]["n"] for t in ext}
    r = q(mig.read_text(encoding="utf-8")); v["apply"] = "ok" if r == [] or (isinstance(r, list) and not any(isinstance(x, dict) and "HTTP_ERROR" in x for x in r)) else r
    if isinstance(r, dict) and "HTTP_ERROR" in r: v["apply"] = r; json.dump(v, open(ev / f"production-apply-domain-{tag}-verification.json", "w"), indent=1); print("APPLY FAILED", r); return 1
    v["mapped"] = q(f"select count(*) n from public.t3a_field_physical_map where qualified_name like '{domain}.%'")[0]["n"]
    v["dt01"] = q("select resolved, unmapped, passes from public.t3a_field_registry_dt01()")[0]
    v["rows_after"] = {t: q(f"select count(*) n from public.{t}")[0]["n"] for t in ext}
    if probe:
        res = q(Path(probe).read_text(encoding="utf-8")); v["probe"] = res
    v["new_tables_rows"] = {t: q(f"select count(*) n from public.{t}")[0]["n"] for t in news}
    json.dump(v, open(ev / f"production-apply-domain-{tag}-verification.json", "w"), indent=1, default=str)
    # rollback
    out = f"-- Rollback for {mig.name} (Domain {domain}). Generated by tools/day1/apply_domain.py after the production apply.\n"
    for t in plan.TABLES:
        if not t.get("extend"): continue
        cols = []
        for fs in t["fields"]:
            f = F[fs["q"]]
            if not fs.get("exists"): cols.append(fs.get("col", f["field"]))
            if f["if_absent"] == "STATE" and f["capture_state_field"]: cols.append(f["capture_state_field"])
        out += f"drop trigger if exists t3a_capture_state_fill on public.{t['name']};\ndrop trigger if exists t3a_2_required_fields_trg on public.{t['name']};\n"
        if cols: out += f"alter table public.{t['name']} " + ", ".join(f"drop column if exists {c}" for c in cols) + ";\n"
    logic = (ROOT / f"tools/day1/plans/domain_{tag}_logic.sql")
    txt = logic.read_text(encoding="utf-8") if logic.exists() else ""
    for m in re.finditer(r"create trigger (\w+) \w+ [^;]*? on (?:public\.)?(\w+)", txt, re.I | re.S): out += f"drop trigger if exists {m.group(1)} on public.{m.group(2)};\n"
    if news: out += "drop table if exists " + ", ".join(f"public.{t}" for t in news) + " cascade;\n"
    for m in re.finditer(r"create table if not exists public\.(\w+)", txt, re.I): out += f"drop table if exists public.{m.group(1)} cascade;\n"
    out += f"delete from public.t3a_field_physical_map where qualified_name like '{domain}.%';\n"
    for m in re.finditer(r"create or replace function public\.(\w+)\(([^)]*)\)", txt, re.I | re.S):
        args = ",".join(re.sub(r"^\s*\w+\s+", "", a.strip().split(" default ")[0]) if a.strip() else "" for a in m.group(2).split(",")) if m.group(2).strip() else ""
        out += f"drop function if exists public.{m.group(1)}({args});\n"
    (ev / f"rollback_day1_domain_{tag}.sql").write_text(out, encoding="utf-8")
    print(json.dumps({k: v[k] for k in ("apply", "mapped", "dt01", "rows_before", "rows_after")}, default=str)); 
    if probe: print("probe:", json.dumps(v["probe"])[:400])
    return 0

if __name__ == "__main__":
    a = [x for x in sys.argv[1:] if not x.startswith("--")]
    probe = sys.argv[sys.argv.index("--probe") + 1] if "--probe" in sys.argv else None
    sys.exit(main(a[0].upper(), probe))
