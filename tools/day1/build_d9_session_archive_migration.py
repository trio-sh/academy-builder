#!/usr/bin/env python3
"""The D9 Session Archive content migration: loads the content package of the dimension as inactive draft records, the way the D4 content was loaded (20261228000000).

  python3 tools/day1/build_d9_session_archive_migration.py <T3A-D9-...-Session-Archive-Content.json> <out.sql>

Every record is a draft for founder approval: no approval, no effective date, no active status. The activation flag stays off. The statements are plain inserts into the append only
registry table, with the same record keys the package loader (t3a_lsa_load_package) uses, so the load is the same as the loader's and a second run writes nothing."""
import json, sys
from pathlib import Path

pkg = json.load(open(sys.argv[1])); out = sys.argv[2]
pid, dim = pkg["package_id"], pkg["dimension_id"]
KEY = {"families": "family_id", "direction_rules": "rule_id", "sufficiency_rules": "rule_id", "entries": "entry_id", "history_rules": "rule_id", "dimension_rules": "rule_id", "dimension_entries": "entry_id"}
lit = lambda s: "'" + str(s).replace("'", "''") + "'"
rows = []
for reg, kf in KEY.items():
    for r in pkg["registries"].get(reg, []):
        assert r.get("status") == "draft_for_approval" and r.get("approved_by") is None and r.get("approved_at") is None, (reg, r.get(kf))
        rows.append(f"  ({lit(reg)}, {lit(r[kf])}, {int(r.get('version', 1))}, {lit(r.get('dimension_id', dim))}, 'draft_for_approval', {lit(pid)}, {lit(json.dumps(r, ensure_ascii=False))}::jsonb)")
for k, v in pkg.get("state_mapping", {}).items():
    rows.append(f"  ('state_mapping', {lit(k)}, 1, {lit(dim)}, 'draft_for_approval', {lit(pid)}, {lit(json.dumps(v, ensure_ascii=False))}::jsonb)")
head = (f"-- {dim} Session Archive content ({pid} v{pkg['version']}): loaded as inactive draft records for CE-D9-07 and CE-D9-08. Status: draft for founder approval.\n"
        f"-- Generated by tools/day1/build_d9_session_archive_migration.py from tools/lsa/fixtures/d9-session-archive-content.json. No record carries an approval, an effective date or an active status; the activation flag stays off.\n"
        "-- No direction rule exists for REK-D9-002 or REK-D9-003: a direction between stating a change and keeping the approach would make change the answer key (decision register row 0.6.25, test D9-71).\n")
Path(out).write_text(head + "insert into public.t3a_lsa_registry_record(registry, record_key, version, dimension_id, status, package_id, body) values\n" + ",\n".join(rows) + "\non conflict (registry, record_key, version) do nothing;\n", encoding="utf-8")
print("wrote", out, len(rows), "records")
