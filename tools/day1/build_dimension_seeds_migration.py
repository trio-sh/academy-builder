#!/usr/bin/env python3
"""Step 5a: the seeds one dimension needs once its content is loaded (the shared machinery of step 4a reads these).

  python3 tools/day1/build_dimension_seeds_migration.py D4 <Build-Package.json> <out.sql> --item-base 28 --blockers ST-D4-010,ST-D4-015 \
      --cross owned,caused,blamed,prioritized,"sequenced the work",checked,verified,escalated --stage1-barred Q-D4-07,Q-D4-07b

Emits: interaction pattern families from the situation classes, the platform cooldown ladder, the closed retired list, the dimension specific checklist items, the recurrence blockers,
the words that belong to other dimensions, the stage form barred questions, and the structural rows of the question definition register (the five semantic fields stay empty)."""
import argparse, json
ap = argparse.ArgumentParser()
ap.add_argument("dim"); ap.add_argument("pkg"); ap.add_argument("out")
ap.add_argument("--item-base", type=int, required=True)
ap.add_argument("--req24", default=None); ap.add_argument("--req25", default=None)  # the dimension's own checklist wording, when its edition states one (D9); the default is the D2 to D4 wording
ap.add_argument("--blockers", default=""); ap.add_argument("--cross", default=""); ap.add_argument("--stage1-barred", default="")
a = ap.parse_args()
dim = a.dim
R = json.load(open(a.pkg))["registers"]
lit = lambda s: "'" + str(s).replace("'", "''") + "'"
fam = ",\n".join(f"  ({lit(dim)},{lit(k)},{lit(v['pattern_family'])})" for k, v in R["situation_classes"].items())
blk = [x for x in a.blockers.split(",") if x]
cross = [x for x in a.cross.split(",") if x]
barred = [x for x in a.stage1_barred.split(",") if x]
n1, n2 = a.item_base, a.item_base + 1
ph = ",\n".join(f"  ({lit(dim)},{lit(n)},{lit(v['kind'])},{lit(v.get('bound_to') or '')},{lit(v.get('grammar') or '')})" for n, v in R["placeholder_grammar"].items())
out = f"""-- Step 5a: the seeds {dim} needs once its content is loaded. Generated by tools/day1/build_dimension_seeds_migration.py. Do not edit by hand.
-- Nothing here approves, activates or serves anything. The five semantic fields of the question definition register stay empty.

insert into public.t3a_dimension_placeholder(dimension_id, placeholder_name, kind, bound_to, grammar) values
{ph}
on conflict do nothing;

insert into public.t3a_interaction_pattern_family(dimension_id, situation_class, interaction_pattern_family_id) values
{fam}
on conflict do nothing;

insert into public.t3a_d1_specification_cooldown (dimension_id, completed_observations, wait_days, issued_under, note)
  select {lit(dim)}, completed_observations, wait_days, issued_under, {lit(dim + ' 4.1 restates the platform ladder (T3A-D1-EXEC-CORR-006 Section 8)')} from public.t3a_d1_specification_cooldown where dimension_id = 'D1'
  on conflict do nothing;

insert into public.t3a_rce_prohibited_vocabulary (dimension_id, word, version, reason)
  select {lit(dim)}, word, {lit('PV-' + dim + '-4.2')}, {lit(dim + ' Section 4.2 retired vocabulary, closed list')} from public.t3a_rce_prohibited_vocabulary where dimension_id = 'D2' and version = 'PV-D2-4.2'
  on conflict do nothing;

alter table public.t3a_dimension_review_item drop constraint if exists t3a_dimension_review_item_item_no_check;
alter table public.t3a_dimension_review_item add constraint t3a_dimension_review_item_item_no_check check (item_no between 1 and {n2});
insert into public.t3a_dimension_review_item (item_no, dimension_id, requirement, display_no) values
  ({n1}, {lit(dim)}, {lit(a.req24 or (dim + ' specific: no rendered ' + dim + ' sentence uses a verb of purpose or disposition (checked against the Section 3.2 prohibited-verb list on rendered output).'))}, 24),
  ({n2}, {lit(dim)}, {lit(a.req25 or (dim + ' specific: no element of the report is computed across dimensions, and no rendered ' + dim + ' sentence names a third party.'))}, 25)
on conflict do nothing;
"""
if blk:
    out += f"\nupdate public.t3a_d1_statement_library set recurrence_blocker = true where dimension_id = {lit(dim)} and statement_key in ({', '.join(lit(x) for x in blk)});\n"
if cross:
    out += f"\nupdate public.t3a_rce_prohibited_vocabulary set reason = 'cross_dimension_assertion' where dimension_id = {lit(dim)} and version = {lit('PV-' + dim + '-1.0')} and word in ({', '.join(lit(x) for x in cross)});\n"
if barred:
    out += f"\ninsert into public.t3a_stage_form_question(dimension_id, question_code, reason) values\n" + ",\n".join(f"  ({lit(dim)},{lit(q)},'a written response cannot evidence it at Stage 1')" for q in barred) + "\non conflict do nothing;\n"
out += f"""
insert into public.t3a_question_definition(dimension_id, question_id, answer_id, exact_stem, stage_applicability, required_or_conditional, missing_state_route, child_branch_rule, statement_mapping)
select m.dimension_id, m.question_code, 'A' || l.line_order, cs.title,
       (select string_agg(distinct unnest_s, ',' order by unnest_s) from (select unnest(coalesce(s.applicable_stages, array[s.stage_code::text])) unnest_s from public.t3a_d1_statement_library s where s.dimension_id = m.dimension_id and s.question_code = m.question_code and s.answer_code = 'A' || l.line_order) z),
       case when exists (select 1 from public.t3a_d1_branch_rule b where b.dimension_id = m.dimension_id and b.child_question = m.question_code) then 'conditional' else 'required' end,
       'platform missing state codes',
       (select b.parent_question || ' ' || array_to_string(b.serving_answers, ',') from public.t3a_d1_branch_rule b where b.dimension_id = m.dimension_id and b.child_question = m.question_code),
       (select string_agg(s.statement_key, ',' order by s.statement_key) from public.t3a_d1_statement_library s where s.dimension_id = m.dimension_id and s.question_code = m.question_code and s.answer_code = 'A' || l.line_order)
  from public.t3a_d1_question_capture_map m
  join public.t3a_d1_capture_set cs on cs.dimension_id = m.dimension_id and cs.capture_set_code = m.capture_set_code
  join public.t3a_d1_capture_line l on l.dimension_id = m.dimension_id and l.capture_set_code = m.capture_set_code
 where m.dimension_id = {lit(dim)}
on conflict do nothing;
"""
open(a.out, "w").write(out)
print(f"{dim}: {len(R['situation_classes'])} situation classes, items {n1} and {n2}, {len(blk)} blockers, {len(cross)} cross dimension words, {len(barred)} barred questions")
