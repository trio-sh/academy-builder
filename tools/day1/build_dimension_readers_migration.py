#!/usr/bin/env python3
"""Step 3a: build migration 20261204 (dimension-aware D1 readers) from the live function definitions.

  python3 tools/day1/build_dimension_readers_migration.py <defs.json>

<defs.json> maps function name to pg_get_functiondef text read from production before the migration. Every edit asserts that it
matched, so a drift in the live definition stops the build. Functions that read by a dimension they can see (a map row, the
Stage entry, the new row) use it; the D1 specific logic (hard coded Q-D1 codes, C2/C8a/C8b, the L-D1 templates) is pinned to
'D1' by wrapping each structure table reference in a dimension filter, so rows of another dimension can never reach it."""
import json, re, sys
from pathlib import Path

defs = json.load(open(sys.argv[1]))
OUT = Path(__file__).resolve().parents[2] / "supabase/migrations/20261204000000_step3_dimension_readers.sql"
out = []

def edit(name, pairs, regex=()):
    d = defs[name]
    for a, b in pairs:
        assert d.count(a) >= 1, f"{name}: no match for {a[:60]!r}"
        d = d.replace(a, b)
    for pat, rep in regex:
        d, n = re.subn(pat, rep, d)
        assert n >= 1, f"{name}: no regex match for {pat!r}"
    return d

def pin(d, dimexpr, tables):
    """Wrap `public.t3a_d1_T alias` (or bare `public.t3a_d1_T`) in a dimension filtered subquery."""
    for t in tables:
        full = f"public.t3a_d1_{t}"
        def sub(m):
            alias = m.group(1)
            if alias and alias.upper() not in ("LOOP", "WHERE", "GROUP", "ON", "LEFT", "JOIN", "ORDER", "CROSS", "INNER"):
                return f"(SELECT * FROM {full} WHERE dimension_id = {dimexpr}) {alias}"
            return f"(SELECT * FROM {full} WHERE dimension_id = {dimexpr}) {t}" + (" " + alias if alias else "")
        d = re.sub(re.escape(full) + r"(?![A-Za-z_])(?:[ \t]+([A-Za-z_][A-Za-z0-9_]*))?", sub, d)
    return d

# helper
out.append("""-- Step 3a: the D1 readers become dimension aware (CR-076). Generated by tools/day1/build_dimension_readers_migration.py from the live definitions.
-- D1 output is unchanged; rows of another dimension can no longer reach D1 logic, and readers that can see their dimension use it.

create or replace function public.t3a_source_dimension(p_source_version_id uuid) returns text language sql stable security definer set search_path = public as $fn$
  select coalesce((select o.dimension_id::text from public.t3a_d1_content_version v join public.t3a_content_object o on o.content_object_id = v.content_object_id where v.content_version_id = p_source_version_id), 'D1')
$fn$;
create or replace function public.t3a_event_dimension(p_stage_entry_event_id uuid) returns text language sql stable security definer set search_path = public as $fn$
  select coalesce((select e.dimension_id::text from public.t3a_stage_entry_event e where e.stage_entry_event_id = p_stage_entry_event_id), 'D1')
$fn$;
""")

W = "AND l.dimension_id = v_map.dimension_id"
out.append(edit("t3a_d1_capture_for_question", [
    ("WHERE l.capture_set_code = v_map.capture_set_code;", f"WHERE l.capture_set_code = v_map.capture_set_code {W};"),
    ("WHERE m2.capture_set_code = v_map.capture_set_code;", "WHERE m2.capture_set_code = v_map.capture_set_code AND m2.dimension_id = v_map.dimension_id;")]))
out.append(edit("t3a_d1_serve_capture", [("WHERE l.capture_set_code = v_map.capture_set_code;", f"WHERE l.capture_set_code = v_map.capture_set_code {W};")]))
out.append(edit("t3a_d1_capture_groups", [("GROUP BY m.capture_set_code", "GROUP BY m.dimension_id, m.capture_set_code")]))
out.append(edit("t3a_d1_branch_answers", [("ON l.capture_set_code = m.capture_set_code\n     AND l.line_order", "ON l.capture_set_code = m.capture_set_code\n     AND l.dimension_id = m.dimension_id\n     AND l.line_order")]))
out.append(edit("t3a_d1_beat_advance_permitted", [("AND s.capture_set_code = b.capture_set_code);", "AND s.capture_set_code = b.capture_set_code\n          AND s.dimension_id = b.dimension_id);")]))
out.append(edit("t3a_d1_question_capture_map_guard", [("WHERE q.question_code = NEW.question_code)\n  THEN", "WHERE q.question_code = NEW.question_code AND q.dimension_id = NEW.dimension_id)\n  THEN")]))

# visible_at_beat: dimension from the Stage entry; D1 only special cases stay D1 only
d = edit("t3a_d1_capture_visible_at_beat", [
    ("  v_disclosed   boolean;\nBEGIN", "  v_disclosed   boolean;\n  v_dim         text := public.t3a_event_dimension(p_stage_entry_event_id);\nBEGIN"),
    ("FROM public.t3a_d1_capture_set s WHERE s.capture_set_code = p_capture_set_code;", "FROM public.t3a_d1_capture_set s WHERE s.capture_set_code = p_capture_set_code AND s.dimension_id = v_dim;"),
    ("IF p_capture_set_code = 'C8b' THEN", "IF v_dim = 'D1' AND p_capture_set_code = 'C8b' THEN"),
    ("ON l.capture_set_code = s.capture_set_code AND l.line_order = s.line_order\n       WHERE", "ON l.capture_set_code = s.capture_set_code AND l.line_order = s.line_order AND l.dimension_id = v_dim\n       WHERE"),
    ("IF p_capture_set_code IN ('C2', 'C8a') AND NOT v_answered THEN", "IF v_dim = 'D1' AND p_capture_set_code IN ('C2', 'C8a') AND NOT v_answered THEN")])
out.append(d)

out.append(edit("t3a_d1_capture_selection_guard", [
    ("FROM public.t3a_d1_capture_set s WHERE s.capture_set_code = NEW.capture_set_code;", "FROM public.t3a_d1_capture_set s WHERE s.capture_set_code = NEW.capture_set_code AND s.dimension_id = NEW.dimension_id;"),
    ("WHERE l.capture_set_code = NEW.capture_set_code\n     AND l.line_order = NEW.line_order;", "WHERE l.capture_set_code = NEW.capture_set_code\n     AND l.dimension_id = NEW.dimension_id\n     AND l.line_order = NEW.line_order;"),
    ("ON l.capture_set_code = s.capture_set_code AND l.line_order = s.line_order\n     WHERE", "ON l.capture_set_code = s.capture_set_code AND l.line_order = s.line_order AND l.dimension_id = s.dimension_id\n     WHERE")]))

# version_set: the dimension of the source version
d = edit("t3a_d1_version_set", [
    ("FROM public.t3a_d1_question_object q)", "FROM public.t3a_d1_question_object q WHERE q.dimension_id = public.t3a_source_dimension(p_source_version_id))"),
    ("JOIN public.t3a_d1_capture_line l ON l.capture_set_code = s.capture_set_code)", "JOIN public.t3a_d1_capture_line l ON l.capture_set_code = s.capture_set_code AND l.dimension_id = s.dimension_id\n        WHERE s.dimension_id = public.t3a_source_dimension(p_source_version_id))"),
    ("FROM public.t3a_d1_branch_rule b)", "FROM public.t3a_d1_branch_rule b WHERE b.dimension_id = public.t3a_source_dimension(p_source_version_id))")])
out.append(d)

# D1 logic pinned
d = edit("t3a_d1_compose_observation", [("JOIN public.t3a_d1_statement_library sl ON sl.statement_key = r.statement_key", "JOIN public.t3a_d1_statement_library sl ON sl.statement_key = r.statement_key AND sl.dimension_id = r.dimension_id"),
    ("ON l.capture_set_code = r.capture_set_code AND l.line_order = r.capture_line_order", "ON l.capture_set_code = r.capture_set_code AND l.line_order = r.capture_line_order AND l.dimension_id = r.dimension_id")])
d = pin(d, "'D1'", ["capture_resolution", "condition_precedence"])
out.append(d)

d = defs["t3a_d1_coverage_matrix"].replace("public.t3a_d1_coverage_matrix()", "public.t3a_d1_coverage_matrix(p_dimension_id text DEFAULT 'D1')")
d = pin(d, "p_dimension_id", ["capture_line", "capture_resolution", "statement_library", "condition_precedence"])
d = d.replace("WHERE language_template_id = 'L-D1-NO-001'", "WHERE language_template_id = 'L-' || p_dimension_id || '-NO-001'").replace("'L-D1-NO-001 is withdrawn and absent'::text", "('L-' || p_dimension_id || '-NO-001 is withdrawn and absent')::text")
out.append(("DROP FUNCTION IF EXISTS public.t3a_d1_coverage_matrix();\n" , d))

d = edit("t3a_d1_reference_card", [
    ("  FROM public.t3a_d1_capture_set s\n  LEFT JOIN governing g ON g.capture_set_code = s.capture_set_code;", "  FROM (SELECT * FROM public.t3a_d1_capture_set WHERE dimension_id = v_object.dimension_id::text) s\n  LEFT JOIN governing g ON g.capture_set_code = s.capture_set_code AND v_object.dimension_id::text = 'D1';"),
    ("FROM public.t3a_d1_capture_line l\n                       WHERE l.capture_set_code = s.capture_set_code))", "FROM public.t3a_d1_capture_line l\n                       WHERE l.capture_set_code = s.capture_set_code AND l.dimension_id = s.dimension_id))")])
out.append(d)

# fill the dimension on a capture selection from its Stage entry when the writer does not supply it
out.append("""create or replace function public.t3a_capture_selection_dimension() returns trigger language plpgsql security definer set search_path = public as $fn$
begin
  if new.dimension_id is null then new.dimension_id := public.t3a_event_dimension(new.stage_entry_event_id); end if;
  return new;
end $fn$;""")

text = ""
for o in out:
    if isinstance(o, tuple):
        text += o[0] + o[1].rstrip() + ";\n\n"
    elif o.lstrip().startswith("--") or o.lstrip().startswith("create or replace function public.t3a_source_dimension"):
        text += o.rstrip() + "\n\n"
    elif o.startswith("create or replace function public.t3a_capture_selection_dimension"):
        text += o.rstrip() + "\n" + "drop trigger if exists t3a_0_capture_selection_dimension_trg on public.t3a_d1_capture_selection;\ncreate trigger t3a_0_capture_selection_dimension_trg before insert on public.t3a_d1_capture_selection for each row execute function public.t3a_capture_selection_dimension();\n\n"
    else:
        text += o.rstrip() + ";\n\n"
# capture_groups / coverage_matrix change their argument list or result shape: drop the old forms first where needed
OUT.write_text(text, encoding="utf-8")
print("wrote", OUT, len(text))
