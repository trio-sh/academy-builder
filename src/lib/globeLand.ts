export const MASK_W = 360;
export const MASK_H = 180;

let bits: Uint8Array | null = null;
function decode(): Uint8Array {
  if (bits) return bits;
  const bin = atob(MASK_B64);
  bits = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bits[i] = bin.charCodeAt(i);
  return bits;
}

/** is there land at this latitude and longitude (degrees) */
export function isLand(latDeg: number, lonDeg: number): boolean {
  const x = Math.min(MASK_W - 1, Math.max(0, Math.floor(lonDeg + 180)));
  const y = Math.min(MASK_H - 1, Math.max(0, Math.floor(90 - latDeg)));
  const i = y * MASK_W + x;
  return (decode()[i >> 3] & (1 << (i & 7))) !== 0;
}
