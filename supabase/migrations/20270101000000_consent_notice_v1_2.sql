create or replace function public.t3a_consent_notice() returns jsonb language sql stable security definer set search_path = public as $fn$
  select case when t is null or h is null or v is null
              then jsonb_build_object('rendered', false, 'reason', 'consent_notice_unloaded')
              else jsonb_build_object('rendered', true, 'notice_version', v, 'notice_hash', h, 'text', t) end
  from (select
    (select nullif(configuration_value, '') from public.t3a_configuration_value where configuration_key = 'consent_notice_text' order by configuration_seq desc limit 1) as t,
    (select nullif(configuration_value, '') from public.t3a_configuration_value where configuration_key = 'consent_notice_hash' order by configuration_seq desc limit 1) as h,
    (select nullif(configuration_version, '') from public.t3a_configuration_value where configuration_key = 'consent_notice_text' order by configuration_seq desc limit 1) as v) x
$fn$;
revoke all on function public.t3a_consent_notice() from public;
