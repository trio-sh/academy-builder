-- Every consent record carries the loaded notice's version and hash, whatever the caller passed. With no notice loaded the caller's values stand.
create or replace function public.t3a_consent_stamp_notice() returns trigger language plpgsql security definer set search_path = public as $fn$
declare n jsonb;
begin
  n := public.t3a_consent_notice();
  if (n->>'rendered')::boolean then
    new.consent_copy_version := n->>'notice_version';
    new.consent_copy_hash := n->>'notice_hash';
  end if;
  return new;
end $fn$;
drop trigger if exists t3a_consent_stamp_notice on public.t3a_consent_record;
create trigger t3a_consent_stamp_notice before insert on public.t3a_consent_record for each row execute function public.t3a_consent_stamp_notice();
