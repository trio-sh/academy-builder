2.1. The 3rd Academy runs structured workplace pressure moments, situations we design and administer, and records selected responses and actions within them. We do not collect observations from your past or current employment.

2.2. The record describes what you did, or said you would do, in specific situations. Where you were asked what you would do, the record says that it is what you said, not something you were seen doing. It does not score, rate or rank you. It does not say what kind of person you are, and it does not predict how you would do in a job. Whether what it describes suits a particular role is for a reader to judge, not for us to say.

### What happens in each part

2.3. **Written situations.** You read a situation on screen and write your response. The situation is shown exactly as written, by a fixed automated process that generates nothing. A trained person we call a mentor then confirms what your written response contains before anything enters your record.

2.4. **A live session.** You take part in a short structured conversation with a mentor on Google Meet. The mentor follows a script. The session is not recorded; the mentor records answers to fixed questions while it happens.

2.5. **A piece of work.** You produce a piece of work from a brief and submit it. A mentor reviews what you submitted. We record what the work shows, not how long it took or how it was made, and we ask you to say whether you used any tool such as artificial intelligence.

2.6. **A group session.** You take part in a live session on Google Meet with a mentor and other people who play set roles. Only you are observed. The session is not recorded. Other people in the session will see and hear what you say.

