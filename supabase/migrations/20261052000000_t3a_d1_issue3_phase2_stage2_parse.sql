-- ---------------------------------------------------------------------
-- 1. Where a per-beat binding lives
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.t3a_d1_beat_capture_binding (
  source_identifier    text NOT NULL,
  beat_code            text NOT NULL,
  capture_set_code     text NOT NULL
    REFERENCES public.t3a_d1_capture_set(capture_set_code) ON DELETE RESTRICT,
  revisable            boolean NOT NULL DEFAULT false,
  qualifier_as_written text,
  PRIMARY KEY (source_identifier, beat_code, capture_set_code)
);

COMMENT ON TABLE public.t3a_d1_beat_capture_binding IS
  'CS-I-51. Which capture sets a beat brings into reach, translated from the superseded eight-set script labels into the current thirteen-set register. The FK to t3a_d1_capture_set is the CS-I-51c check made structural: a binding outside the register cannot be stored at all. Candidates only — CS-I-51a leaves applicability to govern what is actually served.';

COMMENT ON COLUMN public.t3a_d1_beat_capture_binding.revisable IS
  'CS-I-51b. True only where the script wrote "update", and then for EVERY set listed before it in that beat, not only the last. A revisable beat may change an already-captured, uncommitted selection; it never creates a second determination. CS-I-51d: a set bound at several beats WITHOUT update is one determination that becomes available at the first bound beat and holds — re-showing the control later is not an invitation to revise it.';

COMMENT ON COLUMN public.t3a_d1_beat_capture_binding.qualifier_as_written IS
  'The qualifier exactly as the script wrote it. "update" is defined by CS-I-51b. "final" appears at B7 on SRC-D1-S2-005 and SRC-D1-S2-010 and is defined NOWHERE — it is stored so it is not lost and given no behavior, pending a founder instruction. A build does not invent the meaning of an instruction it was not given.';

ALTER TABLE public.t3a_d1_beat_capture_binding ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS t3a_d1_beat_capture_binding_read ON public.t3a_d1_beat_capture_binding;
CREATE POLICY t3a_d1_beat_capture_binding_read
  ON public.t3a_d1_beat_capture_binding FOR SELECT USING (true);

DROP POLICY IF EXISTS t3a_d1_beat_capture_binding_write ON public.t3a_d1_beat_capture_binding;
CREATE POLICY t3a_d1_beat_capture_binding_write
  ON public.t3a_d1_beat_capture_binding FOR INSERT
  WITH CHECK (public.t3a_is_service_context());

GRANT SELECT ON public.t3a_d1_beat_capture_binding TO authenticated;

