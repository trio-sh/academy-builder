-- CS-I-42 is withdrawn FOR STAGE 2 ONLY. It said the Stage 2 production
-- mentor action sequences were content authoring outside the build. They
-- are not: all ten of SRC-D1-S2-001 to SRC-D1-S2-010 carry a complete
-- seven-beat script in the issued Execution Edition, flattened by the
-- source-to-markdown conversion. Stage 3 genuinely has no live sequence
-- and CS-I-42 STANDS there. Stage 4 has complete scripts but its second
-- beat is B2 ROUND, so its loading is DEFERRED to REC-12.
--
-- Generated by scripts/extract-d1-stage2-scripts.mjs.
--
-- THE PARSER READS THE DATABASE, NOT A FILE. It parses the stored
-- `verbatim` of each source's CURRENT version — the text that carries a
-- standing REC-07 approval. The issued document is no longer on disk in
-- this environment, and parsing a copy would have risked exactly what
-- CS-I-48 was added for: work that goes green against text the register
-- has already superseded. The verbatim is read and never written.
--
-- WHAT WAS FOUND THAT SECTION 6.1 DOES NOT COVER, AND NOT DECIDED HERE.
-- A SECOND BINDING QUALIFIER EXISTS. CS-I-51b defines "update". The
-- scripts also use "final", twice: at B7 on SRC-D1-S2-005 and
-- SRC-D1-S2-010 — the two bearing-interest sources — written "C8 final".
-- No instruction gives it a meaning.
--
-- It is parsed rather than ignored, because ignoring it would have left
-- the words "C8 final" inside content_verbatim, putting a binding into the
-- approved spoken line. It is stored in qualifier_as_written and given NO
-- BEHAVIOR: it is not treated as "update", so it grants no revision, and
-- under CS-I-51d C8 is already bound at B2 without "update", so it is one
-- determination that holds from B2 and binding it again at B7 changes
-- nothing that is served. What "final" is meant to mean is recorded for
-- the founder. A build does not get to invent the semantics of an
-- instruction it was not given.
--
-- The parser's qualifier list is CLOSED. A capture list trailed by any
-- other lowercase word refuses that source by name rather than swallowing
-- the word, because a guess there truncates an approved line.
--
-- CS-I-51a — TRANSLATION PRODUCES CANDIDATES; APPLICABILITY STILL GOVERNS.
-- The full translation is stored, and serving filters it. CS-44 requires
-- SRC-D1-S2-001 B3 to be STORED as C1, C2, C3, C4a, C4b — including C4b,
-- on a source whose attribution support set is empty — so the drop cannot
-- happen at store time or that test could not pass. The existing serve
-- path already drops a set the source does not serve, and absence is not a
-- missing state.
--
-- CS-I-52 — is_decision_point is false on every row, and stays false. It
-- resolves at serve time from enquiry_point, account_test_point and
-- bearing_interest under CS-I-32, never from a beat's action type or its
-- position. SRC-D1-S2-001 resolves its enquiry point to B3 and its account
-- test to B6 from its own source-sheet fields, not from this table.
--
-- CS-I-54 — the blast radius is asserted BEFORE and AFTER, in this
-- transaction. If parsing the script table changed any source-sheet field
-- value, the parser would be reading script text as sheet content, and
-- this migration aborts rather than reporting it afterwards.
--
-- ANOTHER GAP THIS EXPOSED. CS-I-59 says to AMEND the CS-I-42 conflict
-- register entry and not delete it, and CS-I-60 says to UPDATE the AC-12
-- per-Stage record. Neither existed as data: both lived as prose inside
-- the conflict_note of an evidence row, where the only way to "amend" one
-- is to rewrite a historical record. They are tables now, so an amendment
-- supersedes rather than overwrites.
-- =====================================================================

