-- ---------------------------------------------------------------------
-- 3. CS-I-54 — assert the blast radius, in the same transaction
-- ---------------------------------------------------------------------

DO $blast$
DECLARE
  v_changed text;
  v_beats   int;
  v_srcs    int;
  v_bind    int;
  v_outside int;
BEGIN
  SELECT string_agg(b.identifier, ', ' ORDER BY b.identifier) INTO v_changed
    FROM sheet_before b
    JOIN public.t3a_content_object co ON co.identifier = b.identifier
    JOIN public.t3a_d1_content_version cv
      ON cv.content_object_id = co.content_object_id
     AND cv.superseded_by IS NULL
   WHERE md5(coalesce((cv.body -> 'source_sheet')::text, '')) <> b.sheet_hash;

  IF v_changed IS NOT NULL THEN
    RAISE EXCEPTION 'CS_I_54_SHEET_CHANGED: the parse altered source-sheet values on %. That means script text is being read as sheet content. Nothing is committed.', v_changed;
  END IF;

  -- CS-I-50 / CS-I-55: exactly ten sources, seven beats each.
  SELECT count(*), count(DISTINCT source_identifier) INTO v_beats, v_srcs
    FROM public.t3a_d1_mentor_action_sequence
   WHERE source_identifier ~ '^SRC-D1-S2-0[0-9]+$';

  IF v_srcs <> 10 OR v_beats <> 70 THEN
    RAISE EXCEPTION 'CS_I_50_FAILED: expected ten Stage 2 sources and seventy beats, found % sources and % beats', v_srcs, v_beats;
  END IF;

  IF EXISTS (
    SELECT 1 FROM (
      SELECT source_identifier,
             string_agg(beat_code, ',' ORDER BY beat_ordinal) AS codes
        FROM public.t3a_d1_mentor_action_sequence
       WHERE source_identifier ~ '^SRC-D1-S2-0[0-9]+$'
       GROUP BY source_identifier) g
     WHERE g.codes <> 'B1,B2,B3,B4,B5,B6,B7')
  THEN
    RAISE EXCEPTION 'CS_I_50_FAILED: a Stage 2 source does not read B1 to B7 in order';
  END IF;

  -- CS-I-49a: the nine-beat trap. Reading past **Question applicability**
  -- would pick up the two "- **B5** Q-D1-..." applicability rows, so a
  -- source would carry a beat whose verbatim starts with a question code.
  IF EXISTS (
    SELECT 1 FROM public.t3a_d1_mentor_action_sequence
     WHERE source_identifier ~ '^SRC-D1-S2-0[0-9]+$'
       AND content_verbatim ~ 'Q-D1-')
  THEN
    RAISE EXCEPTION 'CS_I_49a_FAILED: a beat verbatim names a question code, so the parse read past the Question applicability boundary';
  END IF;

  -- CS-I-51c, belt as well as the FK: zero bare C4, C5 or C8.
  SELECT count(*) INTO v_outside
    FROM public.t3a_d1_beat_capture_binding
   WHERE capture_set_code IN ('C4', 'C5', 'C8');
  IF v_outside <> 0 THEN
    RAISE EXCEPTION 'CS_I_51c_FAILED: % bindings still name a superseded eight-set label', v_outside;
  END IF;

  SELECT count(*) INTO v_bind FROM public.t3a_d1_beat_capture_binding;
  RAISE NOTICE 'Stage 2 loaded: % sources, % beats, % bindings', v_srcs, v_beats, v_bind;

  -- CS-I-57 / CS-I-58: nothing outside Stage 2 was touched.
  IF EXISTS (SELECT 1 FROM public.t3a_d1_mentor_action_sequence
              WHERE source_identifier ~ '^SRC-D1-S[34]-') THEN
    RAISE EXCEPTION 'CS_I_57_58_FAILED: a Stage 3 or Stage 4 PRODUCTION source carries a sequence';
  END IF;

  -- CS-I-57a: DEMO-D1-S4-001 stays loaded. Unloading it would drop the
  -- count to twenty-two and remove the Stage 4 demonstration from AC-12.
  IF NOT EXISTS (SELECT 1 FROM public.t3a_d1_mentor_action_sequence
                  WHERE source_identifier = 'DEMO-D1-S4-001') THEN
    RAISE EXCEPTION 'CS_I_57a_FAILED: DEMO-D1-S4-001 is no longer loaded. It is a demonstration source and the Stage 4 production deferral does not touch it';
  END IF;
END;
$blast$;

